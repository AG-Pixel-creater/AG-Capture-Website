const elements = document.querySelectorAll('[data-i18n]');
const themeToggle = document.getElementById('themeToggle');
const langToggle = document.getElementById('langToggle');
const root = document.body;

let currentLanguage = localStorage.getItem('agcapture-lang') || 'en';
let currentTheme = localStorage.getItem('agcapture-theme') || 'light';

function applyTheme(theme) {
  root.classList.toggle('dark-mode', theme === 'dark');
  themeToggle.innerHTML = theme === 'dark' ? '<span class="toggle-icon">🌙</span>' : '<span class="toggle-icon">☀️</span>';
  localStorage.setItem('agcapture-theme', theme);
}

function applyLanguage(language) {
  const langMap = translations[language] || translations.en;

  elements.forEach((element) => {
    const key = element.dataset.i18n;
    if (langMap[key]) {
      element.textContent = langMap[key];
    }
  });

  document.documentElement.lang = language;
  document.body.dir = language === 'ur' ? 'rtl' : 'ltr';
  document.body.setAttribute('dir', document.body.dir);
  langToggle.innerHTML = language === 'ur' ? '<span>EN</span>' : '<span>اردو</span>';
  localStorage.setItem('agcapture-lang', language);
}

themeToggle.addEventListener('click', () => {
  const nextTheme = currentTheme === 'dark' ? 'light' : 'dark';
  currentTheme = nextTheme;
  applyTheme(currentTheme);
});

langToggle.addEventListener('click', () => {
  currentLanguage = currentLanguage === 'ur' ? 'en' : 'ur';
  applyLanguage(currentLanguage);
});

applyTheme(currentTheme);
applyLanguage(currentLanguage);
